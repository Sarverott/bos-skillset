// A draft SKILL.md for each element, from its glossary page and its class in the core.
import { firstSentence, section, title } from "./glossary.mjs";

const CORE_MODELS = "https://github.com/Sarverott/blacksmith-organization-system/tree/master/src/models";
const quote = (text) => `"${text.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

export function composeSkill({ Model, type, page }) {
  const what = section(page, "What it is") || "[`TODO`] no glossary page yet";
  const where = section(page, "Where") || "[`TODO`]";
  const inside = (Model.children ?? []).map((Child) => `- \`${Child.dirname}/\` (${Child.type})`);
  const description = `${firstSentence(what)} Use when creating, finding or handling a BOS ${type}, or when the user mentions a ${type}.`;
  return [
    "---",
    `name: bos-${type}`,
    `description: ${quote(description)}`,
    "---",
    "",
    `# ${title(page) ?? type} (BOS)`,
    "",
    `> Draft generated by \`bos skills draft\` from \`docs/glossary/${type}.md\` and the core's \`${type}\` model.`,
    "> Grow it by hand: it is never overwritten.",
    "",
    "## What it is",
    "",
    what,
    "",
    "## Where",
    "",
    where,
    ...(inside.length ? ["", "## Inside", "", ...inside] : []),
    "",
    "## Handling",
    "",
    `[\`TODO\`] procedures and commands for a ${type}.`,
    "",
    "## References",
    "",
    `- [glossary](../../docs/glossary/${type}.md)`,
    `- [model](${type === "house" ? "../../src/house/class.mjs" : `${CORE_MODELS}/${type}/class.ts`})`,
    "",
  ].join("\n");
}

export const composeSkills = (context) => {
  context.skills = context.elements.map((model) => ({
    type: model.type,
    name: `bos-${model.type}`,
    text: composeSkill(model),
  }));
};
